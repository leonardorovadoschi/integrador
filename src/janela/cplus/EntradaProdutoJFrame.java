    private void calculaPisCofins() {
        BigDecimal aliq;
        BigDecimal valUnitario = format.stringParaDecimal(jTextFieldValorUnitario.getText(), 4);
        BigDecimal quantidade = new BigDecimal(jTextFieldQuantidade.getText());
        BigDecimal valorTotalProduto = valUnitario.multiply(quantidade);
        valorTotalProduto = valorTotalProduto.add(entProd.getValoracrescimorateado());
        valorTotalProduto = valorTotalProduto.subtract(entProd.getValordescontorateado());
        BigDecimal basePisCofins = valorTotalProduto.subtract(format.stringParaDecimal(jTextFieldValorIcmsProduto.getText(), 4));
        jTextFieldBaseCofinsProd.setText(format.bigDecimalParaString(basePisCofins, 4));
        //jTextFieldBaseCofinsProd.setText(text);
        aliq = format.stringParaDecimal(jTextFieldAliqCofinsProd.getText(), 2);
        //base = format.stringParaDecimal(jTextFieldBaseCofinsProd.getText(), 2);
        jTextFieldValorCofinsProd.setText(format.bigDecimalParaString(calculodeValores(aliq, basePisCofins), 4));

        //jTextFieldBasePisProd.setText(format.stringParaStringMoeda(text, 4));
        jTextFieldBasePisProd.setText(format.bigDecimalParaString(basePisCofins, 4));
        aliq = format.stringParaDecimal(jTextFieldAliqPisProd.getText(), 2);
        //base = format.stringParaDecimal(jTextFieldBasePisProd.getText(), 2);
        jTextFieldValorPis.setText(format.bigDecimalParaString(calculodeValores(aliq, basePisCofins), 4));
    }
    
    private void calculaDeferimento() {
        String estadoFornecedorOuCliente = "";
        if (entProd.getCodmoventr().getCodForn() == null) {
            estadoFornecedorOuCliente = entProd.getCodmoventr().getCodcli().getEstado();
        } else {
            estadoFornecedorOuCliente = entProd.getCodmoventr().getCodForn().getEstado();
        }
        List<Calculoicmsestado> listIcmsPorEstado = queryCplus.listcalculoIcmsEstadol("RS", estadoFornecedorOuCliente, entProd.getCodcfop().getCodcfop(), entProd.getCodprod().getCodcalculoicms().getCodcalculoicms());
        for (Calculoicmsestado icms : listIcmsPorEstado) {
            BigDecimal base = format.stringParaDecimal(jTextFieldBaseIcmsProduto.getText(), 4);
            BigDecimal aliIcms = format.stringParaDecimal(jTextFieldAliqIcmsProduto.getText(), 2);
            BigDecimal valorIcmsOperacao = calculodeValores(aliIcms, base).setScale(2, RoundingMode.UP);
            jTextFieldValorIcmsOperacao.setText(format.bigDecimalParaString(valorIcmsOperacao, 4));
            jTextFieldAliqDeferimento.setText(format.bigDecimalParaString(icms.getAliqdiferimento(), 3));
            BigDecimal valorDeferimento = valorIcmsOperacao.multiply(icms.getAliqdiferimento().divide(new BigDecimal("100.00"))).setScale(2, RoundingMode.UP);
            jTextFieldValorIcmsDeferimento.setText(format.bigDecimalParaString(valorDeferimento, 4));
            jTextFieldValorIcmsProduto.setText(format.bigDecimalParaString(valorIcmsOperacao.subtract(valorDeferimento), 4));
            jTextFieldCodBeneficioFiscal.setText("RS052158");
        }
    } 
    
    private BigDecimal calculodeValores(BigDecimal aliquota, BigDecimal base) {
        double aliq = aliquota.doubleValue();
        double bas = base.doubleValue();
        double valor = (aliq * bas) / 100;
        return new BigDecimal(valor);

    }   
    
